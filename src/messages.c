/** O texto no idioma do programa (o português é a chave; sem tradução, fica o original). */
const char *message_text(const char *portuguese)
{
    if (message_language == LANG_PT)
    {
        return portuguese;
    }

    for (size_t i = 0; i < sizeof MESSAGES / sizeof *MESSAGES; i++)
    {
        if (!strcmp(MESSAGES[i][0], portuguese))
        {
            return MESSAGES[i][1];
        }
    }

    return portuguese;
}
